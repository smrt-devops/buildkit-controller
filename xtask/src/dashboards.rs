    #[test]
    fn splice_replaces_only_the_generated_block() {
        let doc = format!("intro\n\n{START}\n\nold\n\n{END}\n\noutro\n");
        let new = splice(&doc, "new").unwrap();
        assert_eq!(new, format!("intro\n\n{START}\n\nnew\n\n{END}\n\noutro\n"));
        assert_eq!(splice(&new, "new").unwrap(), new);
        assert!(splice("no markers", "x").is_err());
    }

